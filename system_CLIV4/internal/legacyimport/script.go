package legacyimport

import (
	"fmt"
	"strings"
)

// BuildScript renders the complete, runnable .sql artifact for one clinic.
//
// Everything lands in ONE transaction: a half-imported clinic is the hardest state to
// recover from, and a guard that fires must undo the whole thing, not part of it.
//
// The output is DETERMINISTIC — the same dumps produce a byte-identical file, with no
// timestamp in the header. That is on purpose: the artifact is meant to be reviewed,
// diffed against the previous attempt, and committed as evidence of what was run.
func BuildScript(in Input) (script string, rep *Report, err error) {
	rep = NewReport(in.ClinicCode)

	batches, userRows, money, err := BuildAll(in, rep)
	if err != nil {
		return "", rep, err
	}

	// BuildAll no longer builds what was not selected, so there is nothing left to trim
	// here. What remains is telling the operator what they chose, and which groups the
	// choice leaves them depending on the target to already have.
	//
	// The unselected groups are named from the GROUP list rather than from leftover SQL:
	// there is no leftover SQL any more, and naming the groups is the more useful sentence
	// anyway — "money was not imported" reads better than five table names.
	if len(in.Groups) > 0 {
		rep.notef("นำเข้าเฉพาะกลุ่ม: %s", strings.Join(in.Groups, ", "))

		var skipped []string
		for _, g := range GroupNames() {
			if !groupSelected(in.Groups, g) {
				skipped = append(skipped, g)
			}
		}
		if len(skipped) > 0 {
			rep.notef("ไม่นำเข้ารอบนี้ (ตามที่เลือก): %s — ไม่ได้อ่านไฟล์ส่วนนั้นเลย ฉะนั้นข้อผิดพลาดในข้อมูลของกลุ่มเหล่านี้จะไม่ทำให้รอบนี้ล้ม",
				strings.Join(skipped, ", "))
		}
		for _, g := range in.Groups {
			for _, dep := range groupDependsOn[strings.ToLower(strings.TrimSpace(g))] {
				if !groupSelected(in.Groups, dep) {
					rep.notef("กลุ่ม %q อ้างของในกลุ่ม %q ที่ไม่ได้นำเข้ารอบนี้ — ปลายทางต้องมีอยู่แล้ว ไม่งั้นแถวจะกำพร้า", g, dep)
				}
			}
		}
	}

	var b strings.Builder

	b.WriteString("-- ══════════════════════════════════════════════════════════════════════════\n")
	b.WriteString("-- Dr.Ease V2 → V4 data import\n")
	b.WriteString(fmt.Sprintf("-- clinic_code : %s\n", in.ClinicCode))
	if in.OwnerUsername != "" {
		b.WriteString(fmt.Sprintf("-- owner       : %s (legacy users.code) → role owner; ทุกบัญชีที่เหลือ → counter_staff\n", in.OwnerUsername))
	}
	b.WriteString("--\n")
	b.WriteString("-- generated by system_CLIV4. Review it, then run it deliberately:\n")
	b.WriteString("--   psql \"$DATABASE_URL\" -v ON_ERROR_STOP=1 -f <this file>\n")
	b.WriteString("--\n")
	b.WriteString("-- RUN IT AS THE TABLE OWNER (the role the migrations run as), not as the\n")
	b.WriteString("-- application role. The script ANALYZEs each table before the next phase looks\n")
	b.WriteString("-- its rows up, and ANALYZE requires ownership — PostgreSQL 16 has no MAINTAIN\n")
	b.WriteString("-- privilege to delegate it. Under the application role each ANALYZE is skipped\n")
	b.WriteString("-- with only a WARNING, and the import still finishes correctly but takes hours\n")
	b.WriteString("-- instead of minutes: measured on a 81,313-bill export, 30 minutes as owner\n")
	b.WriteString("-- against an estimated 4 hours without the statistics. See analyzeTargets.\n")
	b.WriteString("--\n")
	// The insert-only promise is the main reason this artifact is safe to re-run, so it
	// must NOT be printed when the script also deletes. A header that overstates what a
	// file does is worse than no header.
	hasPurge := strings.TrimSpace(batches[EntCourseBoughtPurge]) != ""
	hasFill := strings.TrimSpace(batches[EntPatientAddressFill]) != ""
	if hasPurge || hasFill {
		b.WriteString("-- ⚠ สคริปต์นี้ไม่ใช่ insert-only ทั้งหมด\n")
		if hasPurge {
			b.WriteString("--   • DELETE สิทธิ์คอร์สที่นำเข้าไว้รอบก่อน (course_bought ที่มี migrate_source_ref)\n")
			b.WriteString("--     แล้วสร้างใหม่ทั้งชุดในทรานแซกชันเดียวกัน ตามมติเจ้าของคลินิก\n")
			b.WriteString("--     แถวที่คนสร้างเองในระบบ (migrate_source_ref เป็น NULL) ไม่ถูกแตะ\n")
		}
		if hasFill {
			b.WriteString("--   • UPDATE เติมช่องที่ว่างของ patient_address ที่มีอยู่แล้ว\n")
			b.WriteString("--     ทุกช่องเป็น COALESCE(NULLIF(col,''), ค่าใหม่, col) → เขียนได้เฉพาะช่องที่ว่างจริง\n")
			b.WriteString("--     ช่องที่มีค่าอยู่แล้วเขียนทับไม่ได้ แม้เป็นค่าที่คนแก้ไว้เอง · รันซ้ำไม่เปลี่ยนอะไร\n")
		}
		b.WriteString("--   ส่วนที่เหลือของสคริปต์ยังเป็น insert-only ตามเดิม\n")
	} else {
		b.WriteString("-- Everything is in ONE transaction and every statement is insert-only\n")
		b.WriteString("-- (ON CONFLICT DO NOTHING / NOT EXISTS), so re-running it adds nothing twice.\n")
	}
	b.WriteString("-- No timestamp in this header on purpose: the same dumps must produce an\n")
	b.WriteString("-- identical file so two attempts can be diffed.\n")
	b.WriteString("--\n")
	b.WriteString("-- WHAT WILL BE WRITTEN\n")
	for _, name := range order {
		e, ok := rep.Entities[name]
		if !ok || e == nil {
			continue
		}
		b.WriteString(fmt.Sprintf("--   %-16s %5d statement(s) จาก %d แถวต้นทาง\n", name, e.Statements, e.SourceRows))
	}
	if len(rep.Warnings) > 0 {
		b.WriteString("--\n-- ⚠ WARNINGS — อ่านก่อนรัน\n")
		for _, w := range rep.Warnings {
			b.WriteString("--   " + oneLine(w) + "\n")
		}
	}
	if len(rep.Notes) > 0 {
		b.WriteString("--\n-- NOTES\n")
		for _, n := range rep.Notes {
			b.WriteString("--   " + oneLine(n) + "\n")
		}
	}
	b.WriteString("-- ══════════════════════════════════════════════════════════════════════════\n\n")

	b.WriteString("BEGIN;\n\n")
	b.WriteString(sessionSettings(in.ClinicCode))

	b.WriteString(buildClinicExistsGuard(in.ClinicCode))
	// Gated on accounts actually being WRITTEN, not merely parsed. Since BuildAll started
	// filtering by group, userRows can be full while no user is imported — appointments
	// parse the users table only to learn which doctor_code V4 will accept. Emitting the
	// collision guard then would refuse the run over ids nothing is going to insert.
	_, importingUsers := batches[EntUsers]
	if importingUsers && len(userRows) > 0 {
		keys := []string{RoleKeyOwner, RoleKeyStaff}
		if _, importingDoctors := batches[EntDoctor]; importingDoctors {
			keys = append(keys, RoleKeyDoctor)
		}
		b.WriteString(buildRolePresetsGuard(keys...))
		b.WriteString(buildUsersCollisionGuard(userRows, in))
	}

	// The legacy-id → V4-id map, before anything that resolves a person through it.
	//
	// Emitted whenever the users dump was PARSED, not only when accounts are written: a
	// patients-only run still has to fill patient.user_insert, and it resolves against
	// accounts a previous run created. Without the table those subqueries would fail on a
	// missing relation instead of quietly returning NULL, which is the right failure but a
	// confusing one.
	if len(userRows) > 0 {
		mapSQL, mapErr := buildUserMap(userRows, in, rep)
		if mapErr != nil {
			return "", rep, mapErr
		}
		if mapSQL != "" {
			b.WriteString("-- ── แผนที่บัญชี: id เดิม → id ที่ V4 ออกให้ ──────────────────────────\n")
			b.WriteString(mapSQL)
			// When this run writes the accounts, the fill goes after them — BuildAll appends
			// it to the users batch. When it does not, nothing later will insert a user, so
			// resolving against what is already there belongs here, and an account nobody
			// ever imported is left unresolved rather than refused: a patients-only run into
			// a clinic whose staff were never migrated is a legitimate thing to do.
			if !importingUsers {
				b.WriteString(buildUserMapFill(in.ClinicCode, false))
			}
		}
	}

	// The money block is only guarded when it is actually part of this run: -only
	// catalog must not be blocked by a rule about bills it is not importing.
	//
	// Only guard 4 goes here. Guard 5 asks whether a patient exists, and in a run that
	// carries patients too the answer is created further down this same file — so it is
	// emitted just before the money phase instead. See money_guards.go.
	writingMoney := strings.TrimSpace(batches[EntInvoice]) != ""
	if writingMoney {
		b.WriteString(buildMoneyPreflightGuards(in.ClinicCode, money.invoiceHN, money.receiptHN))
	}

	// One transaction PER GROUP, not one for the whole file.
	//
	// WHY IT HAD TO CHANGE
	//
	// PostgreSQL takes a lock per RELATION — every table, every index, every toast — and holds
	// it until the transaction ends. This script writes to 19 tables and touches 7 more with
	// UPDATE/DELETE/ANALYZE; with their indexes that is well past max_locks_per_transaction,
	// which is 64 by default. Measured on drease_temporary with a 6,439-patient export:
	//
	//   ERROR: out of shared memory
	//   HINT:  You might need to increase max_locks_per_transaction
	//   CONTEXT: INSERT INTO privacy_patient_hn_ownership … privacy_lock_patient_hn() line 49
	//
	// Splitting by ROW COUNT would not have helped: 500 patients hold exactly the same
	// relation locks as 6,439. Only cutting the number of TABLES per transaction does, and a
	// group is the natural boundary — each one writes to a handful.
	//
	// WHAT IS LOST, SAID PLAINLY
	//
	// The file is no longer all-or-nothing. A failure in group N leaves groups 1..N-1
	// committed, and the tenant has to be deleted before another attempt. The owner accepted
	// that on 17 Sep 2026 in preference to raising the server setting.
	//
	// WHAT MUST BE REPEATED AFTER EVERY BEGIN
	//
	// Both settings below are LOCAL to a transaction. Forgetting to re-issue app.clinic_code
	// would not raise anything — the RLS policies would simply match no rows and every
	// INSERT after the first commit would write ZERO rows while psql reported success.
	first := true
	for _, name := range order {
		sqlText, ok := batches[name]
		if !ok || strings.TrimSpace(sqlText) == "" {
			continue
		}
		if !first {
			b.WriteString("-- ── ปิดทรานแซกชันของกลุ่มก่อนหน้า แล้วเปิดใหม่สำหรับกลุ่มถัดไป ──────────\n")
			b.WriteString("-- (ล็อกของ PostgreSQL คิดต่อตาราง ไม่ใช่ต่อแถว การรวมทุกกลุ่มในทรานแซกชัน\n")
			b.WriteString("--  เดียวจึงชน max_locks_per_transaction — ดูคอมเมนต์ใน script.go)\n")
			b.WriteString("COMMIT;\n\nBEGIN;\n")
			b.WriteString(sessionSettings(in.ClinicCode))
		}
		first = false
		// Guard 5, immediately before the first money entity: the patient phase is above
		// (order puts EntPatient well before EntInvoice) so this run's patients are already
		// in the transaction, and no bill has been written yet, so refusing here still
		// costs nothing. A money-only run reaches this with an empty patient batch above
		// and is checked against whatever the target already holds — the original intent.
		if name == EntInvoice && writingMoney {
			b.WriteString("-- ── ตรวจก่อนเขียนเงิน (ด่าน 5) ────────────────────────────────────\n")
			b.WriteString(buildMoneyPatientGuard(in.ClinicCode, money.hns))
		}
		b.WriteString(fmt.Sprintf("-- ── %s ─────────────────────────────────────────────────────────\n", name))
		b.WriteString(sqlText)
		if !strings.HasSuffix(sqlText, "\n\n") {
			b.WriteString("\n")
		}
		b.WriteString(analyzeAfter(name))
	}

	// After the money rows land: check what was actually written, not what was meant to be.
	//
	// These run in the LAST transaction, which is the money group's own, so a failure here
	// still rolls the money back. It no longer takes the whole file with it — the groups
	// committed before it stay. That is the trade the per-group split makes, and the guard is
	// still the thing that stops a wrong total from being kept.
	if writingMoney {
		b.WriteString("-- ── ตรวจยอดเงินหลังเขียน (ด่าน 1–3) ───────────────────────────────\n")
		b.WriteString(buildMoneyVerifyGuards(in.ClinicCode, keySet(money.invoiceHN), keySet(money.receiptHN),
			money.overpaidInSource))
	}

	// Nothing to do to the identity sequence any more: V4 issues every users.id, so it
	// advances by itself. See the note where usersSequenceFix used to live.

	// Running-number counters, last thing before the final COMMIT.
	//
	// Here and not next to the catalog batch for two reasons: it reads catalog_item back
	// with max(), so every catalog row of this run must already be in the transaction; and
	// it belongs to whichever transaction is still open, which has app.clinic_code set like
	// all the others. Emitted only when this run actually wrote a catalogue — a money-only
	// or patients-only run has no codes to advance past. See sequences.go.
	if strings.TrimSpace(batches[EntCatalogService]) != "" ||
		strings.TrimSpace(batches[EntCatalogCourse]) != "" {
		b.WriteString(buildSequenceBump(in.ClinicCode))
	}

	// catalog_item.sku for the rows this run wrote. Same placement and the same two
	// reasons as the bump above, with one difference in the condition: a drug-only run
	// writes catalog_item rows too, so EntCatalogDrug has to open the gate as well.
	// (It is absent from the bump's condition on purpose — imported stock keeps its V2
	// ST code and mints no CS/LH number.) See catalogsku.go.
	if strings.TrimSpace(batches[EntCatalogService]) != "" ||
		strings.TrimSpace(batches[EntCatalogCourse]) != "" ||
		strings.TrimSpace(batches[EntCatalogDrug]) != "" {
		b.WriteString(buildCatalogSKUIssue(in.ClinicCode))
	}

	b.WriteString("COMMIT;\n")
	script = b.String()

	// STRUCTURAL INVARIANT: never hand out a script that reads a table it did not create.
	//
	// Six places translate a person through import_user_map, and the map is only emitted
	// when a users dump was PARSED. Run `-only patients` without `-users` and the patient
	// rows still carry 4,425 lookups into a table that never exists -- psql then fails on a
	// missing relation after the whole file has been uploaded and started.
	//
	// Checked on the assembled text rather than per entity on purpose: it holds for doctor,
	// clinic_user and clinic_staff too, and for whatever resolves a person next.
	if err := checkUserMapIsCreatedBeforeUse(script); err != nil {
		return "", rep, err
	}
	// STRUCTURAL INVARIANT: no value may be wider than the column it lands in.
	//
	// Also checked on the assembled text, for the same reason as the one above: it holds
	// for every entity, and the cost of finding out later is a half-loaded tenant rather
	// than an error message. See widths.go.
	if err := checkScriptWidths(script, rep); err != nil {
		return "", rep, err
	}
	return script, rep, nil
}

// checkUserMapIsCreatedBeforeUse fails when the script resolves a person through
// import_user_map without the CREATE that makes it exist, which is what forgetting the
// users dump produces.
func checkUserMapIsCreatedBeforeUse(script string) error {
	uses := strings.Count(script, "FROM import_user_map")
	if uses == 0 {
		return nil
	}
	created := strings.Index(script, "CREATE TEMP TABLE import_user_map")
	if created < 0 {
		return fmt.Errorf("ต้องส่งไฟล์ dump ของตาราง users มาด้วย (-users) — %d จุดในสคริปต์นี้ต้องแปลเลขคน "+
			"(เช่น patient.user_insert, doctor.user_id) จาก id เดิมเป็น id ที่ V4 ออกให้ ซึ่งต้องอ่านจากไฟล์ users "+
			"ถ้าไม่ส่งมา สคริปต์จะอ้างตารางที่ไม่มีอยู่แล้วล้มทั้งไฟล์ตอนรัน psql", uses)
	}
	// The CREATE also has to come FIRST. A later one would be a silent no-op: every lookup
	// above it would already have failed.
	if first := strings.Index(script, "FROM import_user_map"); first < created {
		return fmt.Errorf("สคริปต์อ้าง import_user_map ก่อนที่จะสร้างตาราง — ลำดับผิด (ใช้ที่ตำแหน่ง %d, สร้างที่ %d)",
			first, created)
	}
	return nil
}

// analyzeTargets names, per entity, the table that entity FILLS and that a LATER phase
// then looks up one row at a time.
//
// WHY THIS EXISTS — measured, not guessed
// The whole artifact is one transaction, and inside a transaction nothing refreshes
// planner statistics: autovacuum cannot see uncommitted rows and never runs. So after
// the invoice phase has inserted 77,263 rows, pg_class/pg_statistic still describe the
// table the way it was when the transaction opened — in the tenant this was found on,
// 1,767 rows. Every later lookup is planned against that stale picture.
//
// The lookups are exact and every one of them has a matching unique index
// (uniq_invoice_clinic_no on invoice(clinic_code, no), uniq_catalog_item_clinic_code on
// catalog_item(clinic_code, code), items(clinic_code, code)). With a 1,767-row estimate
// Postgres still prefers a Seq Scan, which is a defensible choice for a table that size
// and a catastrophic one for a table that is quietly growing past 77k inside the same
// transaction: invoice_item resolves its invoice_id three times per line × 189,784
// lines, so the cost is quadratic in the number of bills.
//
// Observed on the anjali export (81,313 bills · 189,784 lines) against the test
// database: the invoice phase alone had not finished after 42 minutes and the run was
// abandoned. Re-run with the plans corrected, the same phase finished in ~13 minutes.
//
// ANALYZE is legal inside a transaction and the fresh statistics are visible to the rest
// of it. It reads no business data, writes no row and changes no amount — it only tells
// the planner how big the table has become. That is why it is safe to emit
// unconditionally rather than making the operator pass a flag.
//
// Only tables that a later phase RESOLVES are listed. clinic_user and clinic_staff are
// written from literals and never looked up again, so analysing them would cost time and
// buy nothing.
//
// slot_stock used to be in that sentence and no longer is: the stock_movement phase now
// resolves every lot's id from slot_stock.mongo_id, one lookup per lot, immediately after
// the inserts that created them.
var analyzeTargets = map[string][]string{
	EntUsers:   {"users"},   // clinic_user / clinic_staff resolve the account by id
	EntRoom:    {"room"},    // validate_appointment_assignment reads it per appointment
	EntPatient: {"patient"}, // the money guards and the address fill both join on hn

	EntCatalogService: {"catalog_item"}, // catalog_course_line + invoice_item resolve by code
	EntItems:          {"items"},        // catalog_item(drug) resolves items.id by code
	EntCatalogDrug:    {"catalog_item"},
	EntSlotStock:      {"slot_stock"}, // stock_movement resolves each lot by mongo_id
	EntCatalogCourse:  {"catalog_item"},

	EntInvoice:      {"invoice"},       // invoice_item, receipt, settle and course_bought all resolve it
	EntInvoiceItem:  {"invoice_item"},  // its own NOT EXISTS, and course_bought.invoice_item_id
	EntReceipt:      {"receipt"},       // receipt_payment resolves the receipt by no
	EntCourseBought: {"course_bought"}, // course_bought_items resolves the entitlement it belongs to
	// course_bought_usage resolves its line with a per-row subquery over the rows the
	// items phase just inserted. Without this the planner keeps costing every one of
	// those lookups against an empty table.
	EntCourseBoughtItems: {"course_bought_items"},
}

// analyzeAfter renders the ANALYZE that must follow one entity's statements, or "" when
// nothing later depends on what that entity wrote.
func analyzeAfter(entity string) string {
	tables := analyzeTargets[entity]
	if len(tables) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("-- Refresh planner statistics before the next phase looks these rows up one by one.\n")
	b.WriteString("-- Inside one transaction nothing else will: autovacuum cannot see uncommitted rows,\n")
	b.WriteString("-- so without this the planner keeps costing every lookup against the row count the\n")
	b.WriteString("-- table had when the transaction opened, and picks a Seq Scan over the exact index.\n")
	for _, t := range tables {
		b.WriteString("ANALYZE " + t + ";\n")
	}
	b.WriteString("\n")
	return b.String()
}
